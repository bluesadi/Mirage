static const uint8_t rcon[10] = {
  0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36
};

static uint8_t xtime(uint8_t x){ return (uint8_t)((x<<1) ^ ((x & 0x80)?0x1b:0x00)); }
static uint8_t mul(uint8_t x, uint8_t y){
  // GF(2^8) multiply
  uint8_t r = 0;
  for(int i=0;i<8;i++){
    if (y & 1) r ^= x;
    uint8_t hi = x & 0x80;
    x <<= 1;
    if (hi) x ^= 0x1b;
    y >>= 1;
  }
  return r;
}

static void SubBytes(uint8_t s[16]){ for(int i=0;i<16;i++) s[i] = sbox[s[i]]; }
static void ShiftRows(uint8_t s[16]){
  uint8_t t[16];
  t[0]=s[0]; t[1]=s[5]; t[2]=s[10]; t[3]=s[15];
  t[4]=s[4]; t[5]=s[9]; t[6]=s[14]; t[7]=s[3];
  t[8]=s[8]; t[9]=s[13]; t[10]=s[2]; t[11]=s[7];
  t[12]=s[12]; t[13]=s[1]; t[14]=s[6]; t[15]=s[11];
  memcpy(s,t,16);
}
static void MixColumns(uint8_t s[16]){
  for(int c=0;c<4;c++){
    uint8_t *col=&s[4*c];
    uint8_t a0=col[0],a1=col[1],a2=col[2],a3=col[3];
    col[0] = (uint8_t)(mul(0x02,a0) ^ mul(0x03,a1) ^ a2 ^ a3);
    col[1] = (uint8_t)(a0 ^ mul(0x02,a1) ^ mul(0x03,a2) ^ a3);
    col[2] = (uint8_t)(a0 ^ a1 ^ mul(0x02,a2) ^ mul(0x03,a3));
    col[3] = (uint8_t)(mul(0x03,a0) ^ a1 ^ a2 ^ mul(0x02,a3));
  }
}
static void AddRoundKey(uint8_t s[16], const uint8_t rk[16]){
  for(int i=0;i<16;i++) s[i] ^= rk[i];
}

static void KeyExpansion(const uint8_t key[16], uint8_t roundKeys[11][16]){
  memcpy(roundKeys[0], key, 16);
  for(int r=1;r<=10;r++){
    uint8_t *prev = roundKeys[r-1];
    uint8_t *cur  = roundKeys[r];
    // RotWord + SubWord + Rcon
    uint8_t t0 = sbox[prev[13]] ^ rcon[r-1];
    uint8_t t1 = sbox[prev[14]];
    uint8_t t2 = sbox[prev[15]];
    uint8_t t3 = sbox[prev[12]];
    cur[0] = prev[0] ^ t0;
    cur[1] = prev[1] ^ t1;
    cur[2] = prev[2] ^ t2;
    cur[3] = prev[3] ^ t3;
    for(int i=4;i<16;i++) cur[i] = prev[i] ^ cur[i-4];
  }
}

static void AES128_EncryptBlock(const uint8_t in[16], uint8_t out[16], const uint8_t key[16]){
  uint8_t state[16]; memcpy(state,in,16);
  uint8_t roundKeys[11][16]; KeyExpansion(key, roundKeys);
  AddRoundKey(state, roundKeys[0]);
  for(int r=1;r<=9;r++){
    SubBytes(state);
    ShiftRows(state);
    MixColumns(state);
    AddRoundKey(state, roundKeys[r]);
  }
  SubBytes(state); ShiftRows(state); AddRoundKey(state, roundKeys[10]);
  memcpy(out,state,16);
}

static void print_hex(const uint8_t *b, size_t n){
  for(size_t i=0;i<n;i++) printf("%02x", b[i]);
  printf("\n");
}

static int parse_hex16(const char *hex, uint8_t out[16]){
  if (strlen(hex) != 32) return 0;
  for (int i=0;i<16;i++){
    unsigned int byte;
    if (sscanf(hex+2*i, "%2x", &byte) != 1) return 0;
    out[i] = (uint8_t)byte;
  }
  return 1;
}

int main(int argc, char **argv){
  uint8_t key[16];
  uint8_t pt[16];
  uint8_t exp_ct[16];

  if (argc == 4) {
    if (!parse_hex16(argv[1], key) || !parse_hex16(argv[2], pt) || !parse_hex16(argv[3], exp_ct)){
      fprintf(stderr, "Invalid hex inputs. Use 32-hex chars each.\n");
      return 2;
    }
  } else {
    // NIST SP 800-38A F.1.1 AES-128 ECB example
    uint8_t def_key[16] = { 0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c };
    uint8_t def_pt[16]  = { 0x6b,0xc1,0xbe,0xe2,0x2e,0x40,0x9f,0x96,0xe9,0x3d,0x7e,0x11,0x73,0x93,0x17,0x2a };
    uint8_t def_ct[16]  = { 0x3a,0xd7,0x7b,0xb4,0x0d,0x7a,0x36,0x60,0xa8,0x9e,0xca,0xf3,0x24,0x66,0xef,0x97 };
    memcpy(key, def_key, 16);
    memcpy(pt, def_pt, 16);
    memcpy(exp_ct, def_ct, 16);
  }

  uint8_t ct[16];
  AES128_EncryptBlock(pt, ct, key);
  int ok = memcmp(ct, exp_ct, 16) == 0;
  if (!ok) {
    printf("PT: "); print_hex(pt,16);
    printf("CT: "); print_hex(ct,16);
    printf("EXP: "); print_hex(exp_ct,16);
    printf("Result: FAIL\n");
  }
  return ok?0:1;
}
